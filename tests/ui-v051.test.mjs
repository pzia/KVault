import assert from 'node:assert/strict';
import fs from 'node:fs';
const html=fs.readFileSync('public/index.html','utf8');
const app=fs.readFileSync('public/app.js','utf8');
const storage=fs.readFileSync('public/storage.js','utf8');
const cryptoFile=fs.readFileSync('public/crypto.js','utf8');
const css=fs.readFileSync('public/app.css','utf8');
const worker=fs.readFileSync('src/worker.js','utf8');
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const escapedVersion=pkg.version.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
assert.match(worker,new RegExp(`APP_RELEASE = \"${escapedVersion}\"`));
assert.match(app,new RegExp(`APP_VERSION = '${escapedVersion}'`));
assert.match(html,/id="headerVersion"/);
assert.match(html,/id="appVersion"/);
assert.match(html,/id="workerVersion"/);
assert.match(html,/id="sessionPersistence"/);
assert.match(html,/id="sessionExpiry"/);
assert.match(html,/id="cacheVersion"/);
assert.match(html,/class="lock-icon"/);
assert.doesNotMatch(css.slice(css.lastIndexOf('V0.5.2')),/🔒/);
assert.match(cryptoFile,/encryptDeviceSession/);
assert.match(cryptoFile,/decryptDeviceSession/);
assert.match(storage,/DEVICE_SECRET_KEY\s*=\s*"kobo-vault:device-secret-v2"/);
assert.match(app,/format: 'v2-envelope'/);
assert.match(app,/updateViaCache: 'none'/);
assert.match(app,/controllerchange/);
console.log('ui-v051.test.mjs: OK');
